"""Exercise the HTTP client against a fake server and a generated test fixture.
The fixture is NOT generated by H3 and is never a model-quality benchmark.
"""
import importlib.util
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import threading
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("http_client", ROOT / "scripts/04-generate.py")
client = importlib.util.module_from_spec(spec)
spec.loader.exec_module(client)

@unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"), "requires ffmpeg/ffprobe")
class HTTPTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.work = tempfile.TemporaryDirectory()
        fixture = Path(cls.work.name) / "fixture.mp4"
        subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i",
                        "color=c=black:s=864x480:r=24", "-f", "lavfi", "-i",
                        "anullsrc=r=32000:cl=stereo", "-t", "4", "-c:v", "libx264",
                        "-threads", "1", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
                        "-c:a", "aac", "-shortest", str(fixture)], check=True, timeout=60)
        cls.video_bytes = fixture.read_bytes()
    @classmethod
    def tearDownClass(cls):
        cls.work.cleanup()
    def server(self, content_is_json=False):
        state = {"posts": 0, "polls": 0, "payload": None}
        data = self.video_bytes
        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass
            def send(self, body, content_type="application/json", status=200):
                self.send_response(status)
                self.send_header("Content-Type", content_type)
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            def do_POST(self):
                state["posts"] += 1
                state["payload"] = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
                self.send(json.dumps({"id": "test-job"}).encode())
            def do_GET(self):
                if self.path.endswith("/content"):
                    self.send(b'{"error":"not a video"}' if content_is_json else data,
                              "application/json" if content_is_json else "video/mp4")
                else:
                    state["polls"] += 1
                    status = "in_progress" if state["polls"] == 1 else "completed"
                    self.send(json.dumps({"id": "test-job", "status": status}).encode())
        server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        self.addCleanup(thread.join, 2)
        self.addCleanup(server.server_close)
        self.addCleanup(server.shutdown)
        return f"http://127.0.0.1:{server.server_port}", state
    def test_complete_poll_download_decode(self):
        url, state = self.server()
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "result.mp4"
            payload = client.make_payload("p", "mock prompt", 4, 480, 1)
            record = client.run_job(url, payload, path, timeout_s=30, poll_s=0.01)
            self.assertTrue(path.is_file())
            self.assertEqual(state["posts"], 1)
            self.assertEqual(state["payload"]["num_inference_steps"], 9)
            self.assertEqual(record["status"], "decoded_video_audio_verified")
            self.assertFalse(path.with_name("result.partial.mp4").exists())
    def test_error_json_not_saved_as_video(self):
        url, state = self.server(content_is_json=True)
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "result.mp4"
            payload = client.make_payload("q", "mock prompt", 4, 480, 1)
            with self.assertRaisesRegex(RuntimeError, "text/JSON"):
                client.run_job(url, payload, path, timeout_s=30, poll_s=0.01)
            self.assertFalse(path.exists())
            self.assertEqual(state["posts"], 1)

if __name__ == "__main__":
    unittest.main()
